"""PyABSA ATEPC -> review_aspects rows.

Run under a Python environment where PyABSA is installed (e.g., Python 3.10).
DB id is generated by BIGSERIAL at INSERT time; returned id is None until persisted.
"""

from __future__ import annotations

from typing import Any


# Conservative, extensible mapping. Unknown terms stay None; never guess.
ASPECT_SYNONYMS: dict[str, set[str]] = {
    "hydration": {"hydration", "moisture", "moisturizing", "moisturising", "hydrating", "moisturization"},
    "fragrance": {"fragrance", "scent", "smell", "perfume", "odor", "odour"},
    "absorption": {"absorption", "absorbency", "absorbing"},
    "stickiness": {"stickiness", "sticky", "tackiness", "tacky"},
    "greasiness": {"greasiness", "greasy", "oiliness", "oily residue"},
    "texture": {"texture", "consistency"},
    "price": {"price", "cost"},
    "packaging": {"packaging", "container", "bottle", "pump", "jar"},
    "irritation": {"irritation", "stinging", "burning sensation"},
}

LOOKUP = {
    synonym: standard
    for standard, synonyms in ASPECT_SYNONYMS.items()
    for synonym in synonyms
}


def normalize_aspect(aspect_raw: str) -> str | None:
    """Map an extracted aspect term to a controlled vocabulary, if known."""
    return LOOKUP.get(" ".join(aspect_raw.lower().strip().split()))


def _to_single_result(result: Any) -> dict[str, Any]:
    """Handle PyABSA releases that return either a dict or [dict] for one text."""
    if isinstance(result, list):
        if len(result) != 1:
            raise ValueError(f"Expected one prediction object, got {len(result)}")
        result = result[0]
    if not isinstance(result, dict):
        raise TypeError(f"Unexpected PyABSA output type: {type(result).__name__}")
    return result


class PyABSAEncoder:
    def __init__(self, checkpoint: str = "english") -> None:
        # Deferred import keeps standalone normalization functions testable.
        from pyabsa import AspectTermExtraction as ATEPC
        self.extractor = ATEPC.AspectExtractor(checkpoint=checkpoint)

    def encode(self, review_id: str, text: str) -> list[dict[str, Any]]:
        """Return zero or more `review_aspects` records for one review.

        `id=None` means PostgreSQL should assign BIGSERIAL on INSERT.
        `confidence` is model confidence, not calibrated correctness probability.
        """
        if not review_id:
            raise ValueError("review_id is required")
        if not isinstance(text, str) or not text.strip():
            return []

        prediction = self.extractor.predict(
            text=text,
            pred_sentiment=True,
            print_result=False,
            save_result=False,
        )
        parsed = _to_single_result(prediction)
        aspects = parsed.get("aspect", []) or []
        sentiments = parsed.get("sentiment", []) or []
        confidences = parsed.get("confidence", []) or []

        if not (len(aspects) == len(sentiments) == len(confidences)):
            raise ValueError(
                "PyABSA output arrays have different lengths: "
                f"aspect={len(aspects)}, sentiment={len(sentiments)}, "
                f"confidence={len(confidences)}"
            )

        rows: list[dict[str, Any]] = []
        for aspect, sentiment, confidence in zip(aspects, sentiments, confidences):
            raw = str(aspect).strip()
            if not raw:
                continue
            rows.append({
                "id": None,  # generated by PostgreSQL, NOT the product ASIN
                "review_id": str(review_id),
                "aspect_raw": raw,
                "aspect_normalized": normalize_aspect(raw),
                "sentiment": str(sentiment).strip().lower(),
                "confidence": float(confidence),
            })
        return rows


if __name__ == "__main__":
    from pprint import pprint

    encoder = PyABSAEncoder(checkpoint="english")
    example = (
        "The moisturizing effect is great, but the fragrance is too strong "
        "and the texture feels sticky."
    )
    results = encoder.encode(review_id="R001", text=example)
    pprint(results, sort_dicts=False)
